/**
 * Pixel sprites, authored as text.
 *
 * Each sprite is a list of equal-length rows where `#` is ink and anything else
 * is transparent. Written at half the world size and blitted as 2x2 blocks, so
 * a 23x26 drawing becomes the 46x52 runner the physics already uses — half the
 * rows to author, and chunkier pixels, which is what the original looks like.
 *
 * Drawn in the original's idiom rather than lifted from its sprite sheet.
 */

export const SPRITE_SCALE = 2;

export type Sprite = string[];

/** Width and height in world units, after the 2x blit. */
export const spriteSize = (s: Sprite): { w: number; h: number } => ({
  w: (s[0]?.length ?? 0) * SPRITE_SCALE,
  h: s.length * SPRITE_SCALE,
});

